"""Merge reviewed content from scratch/new_content into the app data modules, sitemap and tests.
Run: python scripts/finalize_content.py
"""
import json, os, re, pprint, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
S = os.path.join(ROOT, "scratch", "new_content")
TODAY = "2026-11-19"
LEGAL_ONLY = "--legal-only" in sys.argv
LANGS = ["ar", "es", "pt", "fr", "de", "id", "it", "ru", "tr", "vi", "ja", "ko", "hi", "my"]
NEW = [
    "youtube-to-mp3-on-iphone-and-android-guide",
    "mp3-bitrate-explained-128-192-256-320-kbps",
    "mp4-vs-webm-mkv-m4a-mp3-format-guide",
    "youtube-copyright-fair-use-creative-commons-guide",
    "find-creative-commons-and-royalty-free-music-on-youtube",
    "save-youtube-shorts-offline-formats-and-best-practices",
    "video-resolution-guide-360p-to-4k-file-size-and-quality",
    "archive-your-own-youtube-uploads-and-lectures-offline",
]
REWRITE = ["youtube-to-mp3-converter-free-guide", "youtube-to-mp4-converter-free-guide"]


def load(*p):
    with open(os.path.join(S, *p), encoding="utf-8") as f:
        return json.load(f)


def thumb(slug):
    return "/static/blog/blog-youtube-to-mp4.jpg" if any(k in slug for k in ("mp4", "video", "shorts", "resolution")) else "/static/blog/blog-youtube-to-mp3.jpg"


def words(h):
    return len(re.sub(r"<[^>]+>", " ", h).split())


missing = []
extra, overrides = [], {}
for slug in ([] if LEGAL_ONLY else NEW + REWRITE):
    en = load("en", slug + ".json")
    assert words(en["content_html"]) >= 1500, (slug, words(en["content_html"]))
    trans = {}
    for l in LANGS:
        fp = os.path.join(S, l, slug + ".json")
        if not os.path.exists(fp):
            missing.append((l, slug))
            continue
        d = load(l, slug + ".json")
        d["slug"] = slug
        d["thumbnail"] = thumb(slug)
        d.setdefault("published_date", d.get("modified_date", ""))
        d.setdefault("modified_date", d["published_date"])
        d["iso_published"] = "2026-11-12" if slug in REWRITE else TODAY
        d["iso_modified"] = TODAY
        trans[l] = d
    base = {k: en[k] for k in ("slug", "title", "meta_desc", "excerpt", "category", "reading_time", "content_html")}
    base.update(thumbnail=thumb(slug), published_date="November 19, 2026", modified_date="November 19, 2026",
                iso_published="2026-11-12" if slug in REWRITE else TODAY, iso_modified=TODAY)
    if slug in REWRITE:
        base["published_date"] = "November 12, 2026"
        for l, d in trans.items():
            pass
    base["translations"] = trans
    (overrides if slug in REWRITE else None) is not None
    if slug in REWRITE:
        overrides[slug] = base
    else:
        extra.append(base)

if missing:
    print("MISSING translations:", len(missing))
    for m in missing[:40]:
        print(" ", m)
    if "--force" not in sys.argv:
        sys.exit(1)

if not LEGAL_ONLY:
    with open(os.path.join(ROOT, "app", "articles_extra.py"), "w", encoding="utf-8", newline="\n") as f:
        f.write("# -*- coding: utf-8 -*-\n# Generated by scripts/finalize_content.py\n\n")
        f.write("NEW_SLUGS = " + pprint.pformat([a["slug"] for a in extra], width=120) + "\n\n")
        f.write("EXTRA_ARTICLES = " + pprint.pformat(extra, width=120) + "\n\n")
        f.write("OVERRIDES = " + pprint.pformat(overrides, width=120) + "\n")

hub = {}
for l in ["en"] + LANGS:
    fp = os.path.join(S, "hub", l + ".json")
    if os.path.exists(fp):
        hub[l] = load("hub", l + ".json")
with open(os.path.join(ROOT, "app", "hub_extra.py"), "w", encoding="utf-8", newline="\n") as f:
    f.write("# -*- coding: utf-8 -*-\n# Generated by scripts/finalize_content.py\n\nHUB_EXTRA = " + pprint.pformat(hub, width=120) + "\n")

legal = {}
for k in ("about-us", "dmca-policy", "editorial-policy"):
    legal[k] = load("legal", k + ".json")
with open(os.path.join(ROOT, "app", "legal_extra.py"), "w", encoding="utf-8", newline="\n") as f:
    f.write("# -*- coding: utf-8 -*-\n# Generated by scripts/finalize_content.py\n\nLEGAL_EXTRA = " + pprint.pformat(legal, width=120) + "\n")

# ---- sitemap ----
base = "https://www.yt4mp3.com"
sp = os.path.join(ROOT, "public", "sitemap.xml")
sm = open(sp, encoding="utf-8").read()
from app.i18n import SUPPORTED_LANGUAGES
codes = list(SUPPORTED_LANGUAGES)


def entry(slug):
    links = [f'    <xhtml:link rel="alternate" hreflang="x-default" href="{base}/blog/{slug}"/>',
             f'    <xhtml:link rel="alternate" hreflang="en" href="{base}/blog/{slug}"/>']
    for c in codes:
        if c != "en":
            links.append(f'    <xhtml:link rel="alternate" hreflang="{c}" href="{base}/{c}/blog/{slug}"/>')
    ls = "\n".join(links)
    out = []
    for c in codes:
        loc = f"{base}/blog/{slug}" if c == "en" else f"{base}/{c}/blog/{slug}"
        out.append(f"  <url>\n    <loc>{loc}</loc>\n    <lastmod>{TODAY}</lastmod>\n{ls}\n  </url>")
    return "\n".join(out)


add = []
for slug in ([] if LEGAL_ONLY else NEW):
    if f"{base}/blog/{slug}<" not in sm:
        add.append(entry(slug))
for k in ("about-us", "dmca-policy", "editorial-policy"):
    if f"{base}/{k}<" not in sm:
        add.append(f"  <url>\n    <loc>{base}/{k}</loc>\n    <lastmod>{TODAY}</lastmod>\n  </url>")
if add:
    sm = sm.replace("</urlset>", "\n".join(add) + "\n</urlset>")


def set_lastmod(sm, pred):
    def rep(m):
        loc = m.group(1)
        return m.group(0) if not pred(loc) else re.sub(r"<lastmod>[^<]+</lastmod>", f"<lastmod>{TODAY}</lastmod>", m.group(0), count=1)
    return re.sub(r"<url>\s*<loc>([^<]+)</loc>.*?</url>", rep, sm, flags=re.S)


tool_re = re.compile(r"^https://www\.yt4mp3\.com/(?:(?:%s)/)?(?:youtube-to-mp3|youtube-to-mp4|youtube-shorts-downloader)?$" % "|".join(codes))


def changed(loc):
    # All site pages received updated footer trust links, scrubbed content, hub sections, or new articles today
    return True


sm = set_lastmod(sm, changed)
open(sp, "w", encoding="utf-8", newline="\n").write(sm)
print("sitemap urls:", sm.count("<url>"))
print("done")
